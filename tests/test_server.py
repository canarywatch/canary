def test_rejects_garbage_and_bad_names():
    with pytest.raises(ValueError):
        manifests.parse("")
    with pytest.raises(ValueError):
        manifests.parse("{not json")
    with pytest.raises(ValueError):
        manifests.parse(json.dumps({"hello": "world"}))
    eco, pairs, _ = manifests.parse(json.dumps({"dependencies": {"../evil": "1", "OK": "1", "fine": "1"}}))
    assert dict(pairs) == {"fine": None}


