def test_pyproject_and_pipfile():
    py = '[project]\nname = "x"\ndependencies = ["requests>=2", "rich==13.7.0"]\n[project.optional-dependencies]\ndev = ["pytest"]\n[tool.poetry.dependencies]\npython = "^3.11"\nhttpx = "0.27.0"\n[tool.poetry.group.dev.dependencies]\nblack = {version = "24.1.0"}\n'
    eco, pairs, fmt = manifests.parse(py)
    assert fmt == "pyproject.toml" and dict(pairs) == {"requests": None, "rich": "13.7.0", "pytest": None, "httpx": "0.27.0", "black": "24.1.0"}
    pf = '[[source]]\nurl = "https://pypi.org/simple"\n[packages]\nrequests = "==2.31.0"\nflask = "*"\n[dev-packages]\npytest = {version = "8.0.0"}\n'
    eco, pairs, fmt = manifests.parse(pf)
    assert fmt == "Pipfile" and dict(pairs) == {"requests": "2.31.0", "flask": None, "pytest": "8.0.0"}


