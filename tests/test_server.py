def test_package_json():
    eco, pairs, fmt = manifests.parse(json.dumps({"name": "app", "dependencies": {"lodash": "^4.17.21", "left-pad": "1.3.0", "@scope/pkg": "~2.0.0"}, "devDependencies": {"jest": "29.0.0"}}))
    assert (eco, fmt) == ("npm", "package.json")
    assert dict(pairs) == {"lodash": None, "left-pad": "1.3.0", "@scope/pkg": None, "jest": "29.0.0"}


def test_package_lock_v3_and_v1():
    v3 = {"name": "app", "lockfileVersion": 3, "packages": {"": {"name": "app"}, "node_modules/lodash": {"version": "4.17.21"}, "node_modules/a/node_modules/b": {"version": "1.0.0"}}}
    eco, pairs, fmt = manifests.parse(json.dumps(v3))
    assert fmt == "package-lock.json" and dict(pairs) == {"lodash": "4.17.21", "b": "1.0.0"}
    v1 = {"name": "app", "lockfileVersion": 1, "dependencies": {"x": {"version": "1.2.3", "dependencies": {"y": {"version": "0.0.1"}}}}}
    assert dict(manifests.parse(json.dumps(v1))[1]) == {"x": "1.2.3", "y": "0.0.1"}


